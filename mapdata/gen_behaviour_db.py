#!/usr/bin/env python3
"""Generate scripts/behaviour_db.gd from data/scripts/behaviourNNN.yaml.

Matches the landstalker-py Behaviour loader (behaviour.py): every script is a
flat list of commands; a command is either a plain string (no parameters) or a
dict {CommandName: {param: value}}. Values are ints, floats or strings.
"""

import glob
import os
import yaml

OUT_PATH = "scripts/behaviour_db.gd"


def fmt_value(value) -> str:
	if value is None:
		return "0"
	if isinstance(value, bool):
		return "true" if value else "false"
	if isinstance(value, (int, float)):
		return str(value)
	if isinstance(value, str):
		return '"%s"' % value.replace('\\', '\\\\').replace('"', '\\"')
	# Nested structures are not produced by the data; stringify defensively.
	return '"%s"' % str(value).replace('"', "'")


def fmt_params(params) -> str:
	if not params:
		return "null"
	body = ",".join('"%s": %s' % (k, fmt_value(v)) for k, v in params.items())
	return "{%s}" % body


def main():
	behaviours = []
	count = 0
	for path in sorted(glob.glob("data/scripts/behaviour*.yaml")):
		name = os.path.basename(path)[len("behaviour"):-5]
		try:
			index = int(name)
		except ValueError:
			print("skip weird name:", path)
			continue
		data = yaml.safe_load(open(path)) or {}
		script = data.get("Script") or []
		commands = []
		for entry in script:
			if isinstance(entry, str):
				commands.append('["%s", null]' % entry)
			elif isinstance(entry, dict):
				assert len(entry) == 1, entry
				key, params = next(iter(entry.items()))
				commands.append('["%s", %s]' % (key, fmt_params(params)))
		behaviour_name = str(data.get("Name", "Behaviour%d" % index))
		behaviours.append("\t%d: [%d, \"%s\", [%s]]," % (
			index, index, behaviour_name, ",".join(commands)))
		count += 1

	with open(OUT_PATH, "w") as out:
		out.write("""## Generated by mapdata/gen_behaviour_db.py from data/scripts/behaviourNNN.yaml.
## Entity behaviour scripts, mirroring landstalker-py behaviour.py.
## Index -> [index, name, script] where script is [[command, params], ...].
class_name BehaviourDb

const BEHAVIOURS := {
%s
}
""" % "\n".join(behaviours))

	print("wrote %s (%d behaviours)" % (OUT_PATH, count))


if __name__ == "__main__":
	main()
