"""Generates scripts/sprite_db.gd from the data/ sprite and entity YAML files.

GDScript has no YAML parser, so the mapping used by landstalker-py
(entity.py/entity_id -> SpriteID -> SpriteGfxNNN label + hitbox) is flattened
once at build time into native dictionaries loaded by scripts/entity_billboard.gd.
Run: python3 mapdata/gen_sprite_db.py
"""
import glob
import os

import yaml

OUT_PATH = os.path.join(os.path.dirname(__file__), "..", "scripts", "sprite_db.gd")

# entity.py spontaneity: item entities use a fixed frame of Anim004
ITEM_FRAMES = {229: (5, "04"), 230: (6, "04")}


def normalize_frame_width(width: float) -> int:
	pixels = int(width * 32)
	for size in (32, 64, 128, 256):
		if pixels <= size:
			return size
	return 256


def main() -> None:
	sprites = []
	for sid in range(108):
		path = f"data/sprites/Sprite{sid:03d}Properties.yaml"
		if not os.path.exists(path):
			continue
		props = yaml.safe_load(open(path))
		animation = props.get("Animation", {})
		hitbox = props.get("Hitbox", {})
		sprites.append(
			"\n	%d: {"
			'"label": "%s",'
			'"width": %s,'
			'"height": %s,'
			'"walk_frames": %d,'
			'"frame_width": %d,'
			"}," % (
				sid,
				props.get("Label", ""),
				hitbox.get("Width", 1.0),
				hitbox.get("Height", 1.0),
				int(animation.get("WalkCycleFrameCount", 1)),
				normalize_frame_width(float(hitbox.get("Width", 1.0))),
			)
		)

	entities = []
	for eid in range(256):
		path = f"data/entities/Entity{eid:03d}Properties.yaml"
		if not os.path.exists(path):
			continue
		props = yaml.safe_load(open(path))
		sprite = int(props.get("SpriteID", 0))
		entities.append(
			"\n	%d: {"
			'"sprite": %d,'
			'"is_item": %s,'
			'"name": "%s",'
			"}," % (
				eid,
				sprite,
				"true" if props.get("IsItem") else "false",
				str(props.get("Name", "")).replace('"', '\\"'),
			)
		)

	items = []
	for eid, (frame, anim) in sorted(ITEM_FRAMES.items()):
		items.append('\n	%d: [%d, "%s"],' % (eid, frame, anim))

	with open(OUT_PATH, "w") as out:
		out.write("""## Generated by mapdata/gen_sprite_db.py from data/ YAML descriptors.
## Maps entity IDs (SpriteID) to the SpriteGfxNNN sheets used by
## scripts/entity_billboard.gd, matching landstalker-py entity.py.
class_name SpriteDb

const SPRITES := {
%s
}

const ENTITIES := {
%s
}

const ITEM_FRAMES := {
%s
}
""" % ("".join(sprites), "".join(entities), "".join(items)))

	print(f"wrote {os.path.normpath(OUT_PATH)} ({len(sprites)} sprites, {len(entities)} entities)")


if __name__ == "__main__":
	main()
